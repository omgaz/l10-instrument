import assert from "node:assert/strict";
import { isColor, isRecord, resolveTokens } from "./tokens.ts";
import type { Source } from "./tokens.ts";

const fields = [
  ["background", "background", "Background Color"],
  ["foreground", "foreground", "Foreground Color"],
  ["cursor", "cursor-color", "Cursor Color"],
  ["cursorText", "cursor-text", "Cursor Text Color"],
  ["selectionBackground", "selection-background", "Selection Color"],
  ["selectionForeground", "selection-foreground", "Selected Text Color"],
] as const;

function itermColor(key: string, color: string): string {
  const components = ["Red", "Green", "Blue"].map(
    (channel, index) =>
      `    <key>${channel} Component</key><real>${parseInt(color.slice(1 + index * 2, 3 + index * 2), 16) / 255}</real>`,
  );
  return `  <key>${key}</key>
  <dict>
    <key>Color Space</key><string>sRGB</string>
    <key>Alpha Component</key><real>1</real>
${components.join("\n")}
  </dict>`;
}

export function compileTerminal(source: Source, mapping: unknown) {
  assert(isRecord(mapping), "Expected a terminal mapping");
  assert.deepEqual(
    Object.keys(mapping).sort(),
    [...fields.map(([key]) => key), "palette"].sort(),
    "Invalid terminal keys",
  );
  return (["light", "dark"] as const).map((mode) => {
    const resolved = resolveTokens(mapping, source.modes[mode]);
    assert(
      isRecord(resolved) && Array.isArray(resolved.palette) && resolved.palette.length === 16,
      "Terminal themes require exactly 16 ANSI palette entries",
    );
    const opaque = (value: unknown): string => {
      assert(
        isColor(value) && (value.length === 7 || value.slice(7).toLowerCase() === "ff"),
        `Terminal themes require opaque hex colors: ${String(value)}`,
      );
      return value.slice(0, 7);
    };
    const palette = resolved.palette.map(opaque);
    const lines = fields.map(([key, ghostty]) => `${ghostty} = ${opaque(resolved[key])}`);
    lines.push(...palette.map((color, index) => `palette = ${index}=${color}`));
    const colors = fields.map(([key, , iterm]) => itermColor(iterm, opaque(resolved[key])));
    colors.push(...palette.map((color, index) => itermColor(`Ansi ${index} Color`, color)));
    return {
      name: `L10 Instrument ${mode === "light" ? "Light" : "Dark"}`,
      ghostty: `# Generated by npm run build. Do not edit.\n${lines.join("\n")}\n`,
      iterm: `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by npm run build. Do not edit. -->
<plist version="1.0">
<dict>
${colors.join("\n")}
</dict>
</plist>
`,
    };
  });
}
